// Generates vendor/ssa-pdf-writer.js, the self-contained iOS writer bundle.
//
// The bundle is a classic script (no import/export) that defines
// globalThis.SsaPdfWriter. It is made from four src/ files — winansi.js,
// manifest.js, addendum-colors.js and pdf-writer.js — by dropping their
// module wiring and wrapping them in an IIFE with a setTimeout shim, because
// JavaScriptCore has no timers and pdf-lib's save() yields with setTimeout(0).
//
// Nobody copies this file by hand: `node tools/build-ios-writer.mjs` rewrites
// the vendor copy, and `--check` exits 1 if it is stale. tests/ios-writer-bundle.js
// and tests/vendor-integrity.js both pin it.

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const REPO = join(dirname(fileURLToPath(import.meta.url)), '..');
const SOURCES = ['src/winansi.js', 'src/manifest.js', 'src/addendum-colors.js', 'src/pdf-writer.js'];
const OUT = join(REPO, 'vendor', 'ssa-pdf-writer.js');

const INTERNAL_SPECIFIERS = new Set(['./winansi.js', './manifest.js', './addendum-colors.js']);

/** The four source files, with module wiring removed. */
function stripModule(text, path) {
  const lines = text.split('\n');
  const out = [];
  for (const line of lines) {
    const trimmed = line.trim();
    if (trimmed.startsWith('import ')) {
      const m = /^import\s+(?:[^'"]*?\s+from\s+)?['"]([^'"]+)['"];?/.exec(trimmed);
      if (!m) throw new Error(`${path}: cannot strip import: ${JSON.stringify(trimmed)}`);
      const specifier = m[1];
      if (!INTERNAL_SPECIFIERS.has(specifier)) {
        throw new Error(`${path}: unexpected import of ${JSON.stringify(specifier)}`);
      }
      continue; // drop the internal import
    }
    if (trimmed.startsWith('export ')) {
      if (/^export\s*\{/.test(trimmed)) throw new Error(`${path}: unexpected re-export: ${JSON.stringify(trimmed)}`);
      if (/^export\s+default\b/.test(trimmed)) throw new Error(`${path}: unexpected export default`);
      if (/^export\s*\*/.test(trimmed)) throw new Error(`${path}: unexpected export *`);
      if (!/^export\s+(async\s+)?(function|const)\b/.test(trimmed)) {
        throw new Error(`${path}: unexpected export form: ${JSON.stringify(trimmed)}`);
      }
      out.push(trimmed.replace(/^export\s+/, ''));
      continue;
    }
    out.push(line);
  }
  return out.join('\n');
}

const WRAPPER_PRE = `// GENERATED by tools/build-ios-writer.mjs from src/winansi.js, src/manifest.js,
// src/addendum-colors.js and src/pdf-writer.js. Do not edit; regenerate.
(function (global) {
  'use strict';
  // JavaScriptCore has no timers. pdf-lib's save() yields with setTimeout(0);
  // a microtask does the same without any host timer.
  if (typeof global.setTimeout !== 'function') {
    global.setTimeout = function (fn) {
      var args = Array.prototype.slice.call(arguments, 2);
      Promise.resolve().then(function () { fn.apply(null, args); });
      return 0;
    };
  }
`;

const WRAPPER_POST = `
  async function fillForHost(templateBytes, planJson, drawListJson, title, creator, updateMetadata) {
    var t0 = Date.now();
    var r = await fillFromPlan(global.PDFLib, templateBytes, {
      plan: JSON.parse(planJson), drawList: drawListJson ? JSON.parse(drawListJson) : null,
      title: title, creator: creator, updateMetadata: updateMetadata !== false
    });
    return { bytes: r.bytes.slice(), missing: r.missing, writeMs: Date.now() - t0 };
  }
  global.SsaPdfWriter = { writeFilledPdf: writeFilledPdf, fillFromPlan: fillFromPlan, fillForHost: fillForHost };
})(globalThis);
`;

/** The bundle text, for tests/ios-writer-bundle.js to compare. */
export function buildIosWriter() {
  const body = SOURCES.map(p => stripModule(readFileSync(join(REPO, p), 'utf8'), p)).join('\n');
  const bundle = WRAPPER_PRE + body + WRAPPER_POST;
  for (const [needle, what] of [
    ['fetch', 'network global'],
    ['XMLHttpRequest', 'network global'],
    ['WebSocket', 'network global'],
    ['require(', 'CommonJS require'],
    ['import(', 'dynamic import']
  ]) {
    if (bundle.includes(needle)) throw new Error(`bundle contains ${what}: ${JSON.stringify(needle)}`);
  }
  return bundle;
}

// -- CLI ---------------------------------------------------------------------

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const bundle = buildIosWriter();
  if (process.argv.includes('--check')) {
    const onDisk = readFileSync(OUT, 'utf8');
    if (onDisk !== bundle) {
      console.error('vendor/ssa-pdf-writer.js is stale; run `node tools/build-ios-writer.mjs`');
      process.exit(1);
    }
    console.log('vendor/ssa-pdf-writer.js is fresh');
    process.exit(0);
  }
  writeFileSync(OUT, bundle);
  console.log(`wrote ${OUT}`);
}
